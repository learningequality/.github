#!/usr/bin/env node
/**
 * Generates .github/workflows/automation.yml, its automation-group-*.yml
 * workflows, and automation-template.yml from automation-registry.yml.
 *
 * Usage:
 *   node scripts/generate-automation.js          regenerate the files
 *   node scripts/generate-automation.js --check  fail (exit 1) if regenerating
 *                                                 would change any file
 */
const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');

const ROOT = path.join(__dirname, '..');
const REGISTRY_PATH = path.join(ROOT, 'automation-registry.yml');
const WORKFLOWS_DIR = path.join(ROOT, '.github', 'workflows');
const GROUP_PREFIX = 'automation-group-';
const TEMPLATE_PATH = path.join(ROOT, 'automation-template.yml');
// This repo is consumer zero: it runs the same template against itself
// instead of a hand-copied caller, so it stays in sync automatically.
const DOGFOOD_PATH = path.join(WORKFLOWS_DIR, 'automation-caller.yml');

const GENERATED_HEADER = (description) => `# This file is generated by scripts/generate-automation.js from automation-registry.yml.
# Do not edit it by hand - edit the registry and run:
#   node scripts/generate-automation.js
#
# ${description}
`;

const DUMP_OPTS = { indent: 2, lineWidth: -1, noRefs: true, quotingType: '"' };

const DEFAULT_PERMISSIONS = { contents: 'read' };
const PERMISSION_RANK = { none: 0, read: 1, write: 2 };
const ACRONYMS = { pr: 'PR' };
// zizmor reports pull_request_target as a dangerous trigger. The hand-written
// callers this template replaces carry the same inline ignore on their `on:` key.
const ZIZMOR_IGNORE = '# zizmor: ignore[dangerous-triggers]';

// js-yaml quotes the top-level `on` key (YAML 1.1 treats on/off as booleans),
// but every hand-written workflow in this repo uses a bare `on:` - match that.
function unquoteOnKey(content, suffix) {
  return content.replace(/^"on":/m, suffix ? `on: ${suffix}` : 'on:');
}

function loadRegistry() {
  const raw = yaml.load(fs.readFileSync(REGISTRY_PATH, 'utf8'));
  return raw.automations.filter((a) => a.enabled);
}

function titleCase(name) {
  return name
    .split('-')
    .map((w) => ACRONYMS[w] || w[0].toUpperCase() + w.slice(1))
    .join(' ');
}

// Omitting types: means all activity types for issues, but only opened,
// synchronize and reopened for pull_request_target.
function mixedTypesError(event, name) {
  return new Error(
    `Event "${event}" is declared both with and without types: (automation "${name}"). ` +
      'Declare types: explicitly on every entry for that event.'
  );
}

function unionPermissions(automations) {
  const merged = {};
  for (const a of automations) {
    for (const [scope, level] of Object.entries(a.permissions || DEFAULT_PERMISSIONS)) {
      const current = merged[scope];
      if (current === undefined || PERMISSION_RANK[level] > PERMISSION_RANK[current]) {
        merged[scope] = level;
      }
    }
  }
  const sorted = {};
  for (const scope of Object.keys(merged).sort()) sorted[scope] = merged[scope];
  return sorted;
}

// secretName -> { required: bool, usedBy: [automationName, ...] }
function collectSecrets(automations) {
  const secrets = {};
  for (const a of automations) {
    for (const [name, mode] of Object.entries(a.secrets || {})) {
      if (!secrets[name]) secrets[name] = { required: false, usedBy: [] };
      if (mode === 'required') secrets[name].required = true;
      secrets[name].usedBy.push(a.name);
    }
  }
  return secrets;
}

function callJob(name, condition, file, permissions, secretNames) {
  const job = {
    name,
    if: `\${{ ${condition} }}`,
    uses: `learningequality/.github/.github/workflows/${file}@main`,
    permissions,
  };
  if (secretNames.length) {
    job.secrets = {};
    for (const s of secretNames) job.secrets[s] = `\${{ secrets.${s} }}`;
  }
  return job;
}

function leafJob(a) {
  const permissions = a.permissions || DEFAULT_PERMISSIONS;
  return callJob(titleCase(a.name), a.if, a.leaf, permissions, Object.keys(a.secrets || {}));
}

function reusableYml(name, automations, jobs, description) {
  const secrets = collectSecrets(automations);
  const secretsYaml = {};
  for (const secret of Object.keys(secrets).sort()) {
    const info = secrets[secret];
    secretsYaml[secret] = {
      description: `Forwarded to: ${info.usedBy.join(', ')}`,
      required: info.required,
    };
  }
  const doc = { name, on: { workflow_call: { secrets: secretsYaml } }, jobs };
  return unquoteOnKey(GENERATED_HEADER(description) + yaml.dump(doc, DUMP_OPTS));
}

function groupByEvents(automations) {
  const groups = new Map();
  for (const a of automations) {
    const key = Object.keys(a.on || {}).sort().join('-').replace(/_/g, '-');
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(a);
  }
  return groups;
}

// GitHub posts a check on the PR for every job in a run, even a skipped one,
// but a skipped call to a reusable workflow posts only one.
function buildReusableWorkflows(automations) {
  const files = {};
  const jobs = {};
  const addJob = (id, job) => {
    if (jobs[id]) throw new Error(`Job id "${id}" is used by both a group and an automation in automation.yml.`);
    jobs[id] = job;
  };

  for (const [key, members] of groupByEvents(automations)) {
    if (members.length === 1) {
      addJob(members[0].name, leafJob(members[0]));
      continue;
    }
    const file = `${GROUP_PREFIX}${key}.yml`;
    const groupJobs = {};
    for (const a of members) groupJobs[a.name] = leafJob(a);
    files[file] = reusableYml(
      `Automation: ${titleCase(key)}`,
      members,
      groupJobs,
      `Reusable workflow called from automation.yml: the automations triggered by ${Object.keys(members[0].on).sort().join(', ')}.`
    );
    addJob(
      key,
      callJob(
        titleCase(key),
        members.map((a) => `(${a.if})`).join(' || '),
        file,
        unionPermissions(members),
        Object.keys(collectSecrets(members)).sort()
      )
    );
  }

  files['automation.yml'] = reusableYml(
    'Automation',
    automations,
    jobs,
    'Reusable workflow: one job per automation, or per group of automations sharing trigger events,\n' +
      '# gated on the original triggering event/action.'
  );
  return files;
}

function unionOn(automations) {
  const on = {};
  for (const a of automations) {
    for (const [event, value] of Object.entries(a.on || {})) {
      if (event === 'schedule') {
        on.schedule = on.schedule || [];
        const entries = Array.isArray(value) ? value : [value];
        for (const entry of entries) {
          const { cron } = entry;
          if (cron && !on.schedule.some((s) => s.cron === cron)) on.schedule.push({ cron });
        }
      } else if (value && Array.isArray(value.types)) {
        if (on[event] && !on[event].types) throw mixedTypesError(event, a.name);
        on[event] = on[event] || { types: [] };
        for (const t of value.types) {
          if (!on[event].types.includes(t)) on[event].types.push(t);
        }
      } else {
        if (on[event] && on[event].types) throw mixedTypesError(event, a.name);
        on[event] = {};
      }
    }
  }
  return sortOn(on);
}

// Consumers hold a copied template, so key order must depend only on the set of
// enabled automations, never on their order in the registry.
function sortOn(on) {
  const sorted = {};
  for (const event of Object.keys(on).sort()) {
    const value = on[event];
    if (Array.isArray(value)) {
      sorted[event] = [...value].sort((a, b) => a.cron.localeCompare(b.cron));
    } else if (value && value.types) {
      sorted[event] = { types: [...value.types].sort() };
    } else {
      sorted[event] = value;
    }
  }
  return sorted;
}

function buildTemplateYml(automations, secrets, description) {
  const secretsForward = {};
  for (const name of Object.keys(secrets).sort()) {
    secretsForward[name] = `\${{ secrets.${name} }}`;
  }

  const doc = {
    name: 'Automation',
    on: unionOn(automations),
    permissions: unionPermissions(automations),
    jobs: {
      automation: {
        name: 'Run automations',
        uses: 'learningequality/.github/.github/workflows/automation.yml@main',
        secrets: secretsForward,
      },
    },
  };
  return unquoteOnKey(GENERATED_HEADER(description) + yaml.dump(doc, DUMP_OPTS), ZIZMOR_IGNORE);
}

function main() {
  const check = process.argv.includes('--check');
  const automations = loadRegistry();

  const secrets = collectSecrets(automations);
  const targets = [
    ...Object.entries(buildReusableWorkflows(automations)).map(([file, content]) => [
      path.join(WORKFLOWS_DIR, file),
      content,
    ]),
    [TEMPLATE_PATH, buildTemplateYml(automations, secrets,
      'Caller template: copy this file to .github/workflows/automation.yml in a consumer repo.\n' +
      '# No edits are needed - the on: block is the exhaustive union of every enabled automation.')],
    [DOGFOOD_PATH, buildTemplateYml(automations, secrets,
      'This repo\'s own automation caller - .github acts as consumer zero and stays in sync automatically.')],
  ];
  const targetPaths = new Set(targets.map(([target]) => target));
  const stale = fs
    .readdirSync(WORKFLOWS_DIR)
    .filter((f) => f.startsWith(GROUP_PREFIX))
    .map((f) => path.join(WORKFLOWS_DIR, f))
    .filter((f) => !targetPaths.has(f));

  if (check) {
    let drifted = false;
    for (const [target, content] of targets) {
      const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
      if (current !== content) {
        console.error(`Drift detected in ${path.relative(ROOT, target)} - run \`node scripts/generate-automation.js\``);
        drifted = true;
      }
    }
    for (const target of stale) {
      console.error(`Stale ${path.relative(ROOT, target)} - run \`node scripts/generate-automation.js\``);
      drifted = true;
    }
    process.exit(drifted ? 1 : 0);
  }

  for (const [target, content] of targets) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
    console.log(`Wrote ${path.relative(ROOT, target)}`);
  }
  for (const target of stale) {
    fs.unlinkSync(target);
    console.log(`Removed ${path.relative(ROOT, target)}`);
  }
}

if (require.main === module) main();

module.exports = { buildReusableWorkflows };
